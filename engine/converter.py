def convert_image(file_path: str, options: ConversionOptions) -> bytes:
    img = PILImage.open(file_path)
    img_width, img_height = img.size

    page_size = get_page_size(options.page_size, options.orientation)
    margin_mm = get_margin_mm(options.margin)

    page_w = page_size[0] - margin_mm * 2 * mm
    page_h = page_size[1] - margin_mm * 2 * mm

    # Fit image to page
    if options.image_fit == "contain":
        ratio = min(page_w / (img_width * 0.75), page_h / (img_height * 0.75))
        display_w = img_width * 0.75 * ratio
        display_h = img_height * 0.75 * ratio
    elif options.image_fit == "cover":
        ratio = max(page_w / (img_width * 0.75), page_h / (img_height * 0.75))
        display_w = img_width * 0.75 * ratio
        display_h = img_height * 0.75 * ratio
    else:
        display_w = min(img_width * 0.75, page_w)
        display_h = min(img_height * 0.75, page_h)

    styles = get_styles()
    pdf_doc, buf, _, _ = build_doc(Path(file_path).stem, options)
    story = []

    add_title(story, Path(file_path).stem, "Image", styles)

    # Save temp image for ReportLab (must exist until build completes)
    tmp_path = os.path.join(tempfile.gettempdir(), f"f2f_img_{uuid.uuid4().hex}{Path(file_path).suffix}")
    img.save(tmp_path)
    rl_img = RLImage(tmp_path, width=display_w, height=display_h)
    story.append(rl_img)
    story.append(Spacer(1, 8))
    story.append(Paragraph(
        f"{img.size[0]} &times; {img.size[1]} px &bull; {Path(file_path).suffix.upper()[1:]}",
        styles["DocSubtitle"]
    ))

    def on_page(canvas, doc):
        add_watermark_to_canvas(canvas, doc, options.watermark)
        if options.add_page_numbers:
            add_page_number(canvas, doc)

    pdf_doc.build(story, onFirstPage=on_page, onLaterPages=on_page)

    if os.path.exists(tmp_path):
        os.unlink(tmp_path)

    return buf.getvalue()


