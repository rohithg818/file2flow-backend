def convert_docx(file_path: str, options: ConversionOptions) -> bytes:
    from docx import Document

    doc = Document(file_path)
    styles = get_styles()
    pdf_doc, buf, page_size, margin_mm = build_doc(
        Path(file_path).stem, options
    )
    story = []

    add_title(story, Path(file_path).stem, "Word Document", styles)

    for para in doc.paragraphs:
        text = para.text.strip()
        if not text:
            story.append(Spacer(1, 6))
            continue

        style_name = para.style.name.lower()

        if "heading 1" in style_name or "title" in style_name:
            story.append(Paragraph(text, styles["SectionHeader"]))
        elif "heading 2" in style_name:
            story.append(Paragraph(text, ParagraphStyle(
                "H2", parent=styles["SectionHeader"], fontSize=13, textColor=HexColor("#2563EB")
            )))
        elif "heading 3" in style_name:
            story.append(Paragraph(text, ParagraphStyle(
                "H3", parent=styles["SectionHeader"], fontSize=11, textColor=HexColor("#1E293B")
            )))
        elif "list" in style_name:
            story.append(Paragraph(f"&bull; {text}", styles["BulletItem"]))
        else:
            # Handle bold runs
            formatted = ""
            for run in para.runs:
                if run.bold:
                    formatted += f"<b>{run.text}</b>"
                elif run.italic:
                    formatted += f"<i>{run.text}</i>"
                else:
                    formatted += run.text
            if formatted:
                story.append(Paragraph(formatted, styles["BodyText2"]))

    # Convert tables
    for table in doc.tables:
        data = []
        for row in table.rows:
            data.append([cell.text for cell in row.cells])

        if data:
            t = Table(data, repeatRows=1)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), HexColor("#1E293B")),
                ("TEXTCOLOR", (0, 0), (-1, 0), white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, 0), 9),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
                ("TOPPADDING", (0, 0), (-1, 0), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("BACKGROUND", (0, 1), (-1, -1), HexColor("#F8FAFC")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [HexColor("#F8FAFC"), white]),
                ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#E2E8F0")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]))
            story.append(Spacer(1, 12))
            story.append(t)
            story.append(Spacer(1, 12))

    def on_page(canvas, doc):
        add_watermark_to_canvas(canvas, doc, options.watermark)
        if options.add_page_numbers:
            add_page_number(canvas, doc)

    pdf_doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


