def convert_pptx(file_path: str, options: ConversionOptions) -> bytes:
    from pptx import Presentation

    prs = Presentation(file_path)
    styles = get_styles()
    pdf_doc, buf, page_size, margin_mm = build_doc(
        Path(file_path).stem, options
    )
    story = []

    add_title(story, Path(file_path).stem, "Presentation", styles)
    story.append(Paragraph(
        f"{len(prs.slides)} slide{'s' if len(prs.slides) != 1 else ''}",
        styles["DocSubtitle"]
    ))

    for i, slide in enumerate(prs.slides):
        story.append(Spacer(1, 12))

        slide_texts = []
        for shape in slide.shapes:
            if shape.has_text_frame:
                for para in shape.text_frame.paragraphs:
                    text = para.text.strip()
                    if text:
                        slide_texts.append(text)

        if not slide_texts:
            continue

        # Slide container
        slide_content = []
        slide_content.append(Paragraph(
            f"SLIDE {i + 1}",
            ParagraphStyle("SlideNum", parent=styles["Normal"], fontSize=8,
                           textColor=HexColor("#2563EB"), fontName="Helvetica-Bold",
                           spaceAfter=6)
        ))

        for j, text in enumerate(slide_texts):
            if j == 0:
                slide_content.append(Paragraph(
                    text, ParagraphStyle("SlideTitle", parent=styles["Normal"],
                                         fontSize=14, leading=18,
                                         textColor=HexColor("#0F172A"),
                                         fontName="Helvetica-Bold",
                                         spaceAfter=6)
                ))
            else:
                slide_content.append(Paragraph(
                    text, ParagraphStyle("SlideBody", parent=styles["Normal"],
                                         fontSize=10, leading=14,
                                         textColor=HexColor("#334155"),
                                         spaceAfter=4)
                ))

        # Wrap in a table for visual box
        inner = []
        for item in slide_content:
            inner.append([item])

        t = Table(inner, colWidths=[page_size[0] - margin_mm * 2 * mm - 16 * mm])
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 1, HexColor("#E2E8F0")),
            ("LEFTPADDING", (0, 0), (-1, -1), 12),
            ("RIGHTPADDING", (0, 0), (-1, -1), 12),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("ROUNDEDCORNERS", [6, 6, 6, 6]),
        ]))
        story.append(t)

    def on_page(canvas, doc):
        add_watermark_to_canvas(canvas, doc, options.watermark)
        if options.add_page_numbers:
            add_page_number(canvas, doc)

    pdf_doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


