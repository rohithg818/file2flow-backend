def convert_json(file_path: str, options: ConversionOptions) -> bytes:
    with open(file_path, "r", encoding="utf-8") as f:
        raw = f.read()

    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        data = None

    styles = get_styles()
    pdf_doc, buf, page_size, margin_mm = build_doc(
        Path(file_path).stem, options
    )
    story = []

    add_title(story, Path(file_path).stem, "JSON Data", styles)

    file_size = len(raw.encode("utf-8"))
    if file_size > 1024:
        size_str = f"{file_size / 1024:.1f} KB"
    else:
        size_str = f"{file_size} B"

    if isinstance(data, list):
        story.append(Paragraph(
            f"{len(data)} items &bull; {size_str}",
            styles["DocSubtitle"]
        ))
    elif isinstance(data, dict):
        story.append(Paragraph(
            f"{len(data)} keys &bull; {size_str}",
            styles["DocSubtitle"]
        ))
    else:
        story.append(Paragraph(size_str, styles["DocSubtitle"]))

    story.append(Spacer(1, 12))

    # If array of objects, render as table
    if isinstance(data, list) and len(data) > 0 and isinstance(data[0], dict):
        all_keys = []
        seen = set()
        for item in data:
            for k in item.keys():
                if k not in seen:
                    all_keys.append(k)
                    seen.add(k)

        # Table view
        story.append(Paragraph("Table View", styles["SectionHeader"]))

        headers = all_keys
        table_data = [headers]
        for item in data[:500]:
            row = []
            for k in all_keys:
                val = item.get(k)
                if val is None:
                    row.append("null")
                elif isinstance(val, (dict, list)):
                    s = json.dumps(val, ensure_ascii=False)
                    row.append(s[:60] + "..." if len(s) > 60 else s)
                else:
                    row.append(str(val))
            table_data.append(row)

        page_w = page_size[0] - margin_mm * 2 * mm
        num_cols = len(headers)
        col_w = page_w / max(num_cols, 1)

        t = Table(table_data, colWidths=[col_w] * num_cols, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), HexColor("#1E293B")),
            ("TEXTCOLOR", (0, 0), (-1, 0), white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, 0), 8),
            ("FONTSIZE", (0, 1), (-1, -1), 7),
            ("FONTNAME", (0, 1), (-1, -1), "Courier"),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
            ("TOPPADDING", (0, 0), (-1, 0), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [HexColor("#F8FAFC"), white]),
            ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#E2E8F0")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(t)
        story.append(Spacer(1, 16))

    # Raw JSON view
    story.append(Paragraph("Raw JSON", styles["SectionHeader"]))
    formatted = json.dumps(data, indent=2, ensure_ascii=False) if data else raw

    # Split into chunks for ReportLab
    max_line_len = 90
    lines = formatted.split("\n")
    for line in lines:
        safe = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        if len(safe) > max_line_len:
            safe = safe[:max_line_len] + "..."
        story.append(Paragraph(f"<font face='Courier' size='8'>{safe}</font>", styles["BodyText2"]))

    def on_page(canvas, doc):
        add_watermark_to_canvas(canvas, doc, options.watermark)
        if options.add_page_numbers:
            add_page_number(canvas, doc)

    pdf_doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


