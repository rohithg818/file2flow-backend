def get_page_size(page_size: str, orientation: str):
    sizes = {"a4": A4, "letter": LETTER, "legal": LEGAL}
    ps = sizes.get(page_size, A4)
    if orientation == "landscape":
        return (ps[1], ps[0])
    return ps


def get_margin_mm(margin: str) -> float:
    margins = {"narrow": 12, "normal": 22, "wide": 32, "none": 8}
    return margins.get(margin, 22)


