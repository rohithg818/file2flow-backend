def build_doc(filename: str, options: ConversionOptions):
    page_size = get_page_size(options.page_size, options.orientation)
    margin_mm = get_margin_mm(options.margin)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=page_size,
        leftMargin=margin_mm * mm,
        rightMargin=margin_mm * mm,
        topMargin=margin_mm * mm,
        bottomMargin=margin_mm * mm,
    )
    return doc, buf, page_size, margin_mm


