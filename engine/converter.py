def convert_html(file_path: str, options: ConversionOptions) -> bytes:
    try:
        from weasyprint import HTML
        page_size = get_page_size(options.page_size, options.orientation)
        margin_mm = get_margin_mm(options.margin)

        html = HTML(filename=file_path)
        pdf_bytes = html.write_pdf()
        return pdf_bytes
    except Exception:
        # Fallback: plain text extraction
        with open(file_path, "r", encoding="utf-8") as f:
            raw = f.read()
        import re
        text = re.sub(r'<[^>]+>', '\n', raw)
        text = re.sub(r'\n{3,}', '\n\n', text).strip()

        tmp = tempfile.NamedTemporaryFile(suffix=".txt", delete=False, mode="w", encoding="utf-8")
        tmp.write(text)
        tmp.close()
        try:
            return convert_text(tmp.name, options)
        finally:
            os.unlink(tmp.name)


