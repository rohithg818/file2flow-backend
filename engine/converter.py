def convert_markdown(file_path: str, options: ConversionOptions) -> bytes:
    import markdown as md

    with open(file_path, "r", encoding="utf-8") as f:
        raw = f.read()

    styles = get_styles()
    pdf_doc, buf, page_size, margin_mm = build_doc(
        Path(file_path).stem, options
    )
    story = []

    add_title(story, Path(file_path).stem, "Markdown", styles)

    # Convert markdown to HTML then parse into ReportLab
    html = md.markdown(raw, extensions=["tables", "fenced_code", "codehilite"])

    # Simple HTML to ReportLab flowables
    from reportlab.platypus import Paragraph as RLPara
    import re

    # Strip HTML tags for simple conversion
    def html_to_flowables(html_content):
        flowables = []
        # Split by block elements
        blocks = re.split(r'\n\s*\n', html_content)
        for block in blocks:
            block = block.strip()
            if not block:
                continue

            # Headers
            h_match = re.match(r'<h(\d)>(.*?)</h\1>', block, re.DOTALL)
            if h_match:
                level = int(h_match.group(1))
                text = re.sub(r'<[^>]+>', '', h_match.group(2))
                if level == 1:
                    flowables.append(Paragraph(text, ParagraphStyle(
                        "MDH1", parent=styles["SectionHeader"], fontSize=18, textColor=HexColor("#0F172A")
                    )))
                elif level == 2:
                    flowables.append(Paragraph(text, ParagraphStyle(
                        "MDH2", parent=styles["SectionHeader"], fontSize=14, textColor=HexColor("#1E40AF")
                    )))
                else:
                    flowables.append(Paragraph(text, ParagraphStyle(
                        "MDH3", parent=styles["SectionHeader"], fontSize=12, textColor=HexColor("#334155")
                    )))
                flowables.append(Spacer(1, 6))
                continue

            # Lists
            if block.startswith("<ul") or block.startswith("<ol"):
                items = re.findall(r'<li>(.*?)</li>', block, re.DOTALL)
                for item in items:
                    text = re.sub(r'<[^>]+>', '', item).strip()
                    flowables.append(Paragraph(
                        f"&bull; {text}", styles["BulletItem"]
                    ))
                flowables.append(Spacer(1, 6))
                continue

            # Code blocks
            if block.startswith("<pre") or block.startswith("<code"):
                code = re.sub(r'<[^>]+>', '', block).strip()
                flowables.append(Paragraph(
                    code.replace("\n", "<br/>").replace(" ", "&nbsp;"),
                    styles["CodeBlock"]
                ))
                continue

            # Paragraph
            text = re.sub(r'<[^>]+>', '', block).strip()
            if text:
                # Handle inline bold/italic
                text_html = block
                text_html = re.sub(r'<strong>(.*?)</strong>', r'<b>\1</b>', text_html)
                text_html = re.sub(r'<em>(.*?)</em>', r'<i>\1</i>', text_html)
                # Strip remaining tags
                text_clean = re.sub(r'<[^>]+>', '', text_html).strip()
                if text_clean:
                    flowables.append(Paragraph(text_clean, styles["BodyText2"]))
                    flowables.append(Spacer(1, 4))

        return flowables

    story.extend(html_to_flowables(html))

    def on_page(canvas, doc):
        add_watermark_to_canvas(canvas, doc, options.watermark)
        if options.add_page_numbers:
            add_page_number(canvas, doc)

    pdf_doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


