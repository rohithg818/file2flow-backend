def convert_spreadsheet(file_path: str, options: ConversionOptions, is_csv: bool = False) -> bytes:
    import pandas as pd

    if is_csv:
        df = pd.read_csv(file_path)
        sheets = {"Sheet1": df}
    else:
        xls = pd.ExcelFile(file_path)
        sheets = {}
        for name in xls.sheet_names:
            sheets[name] = pd.read_excel(xls, sheet_name=name)

    styles = get_styles()
    pdf_doc, buf, page_size, margin_mm = build_doc(
        Path(file_path).stem, options
    )
    story = []

    label = "CSV Data" if is_csv else "Spreadsheet"
    add_title(story, Path(file_path).stem, label, styles)

    for sheet_name, df in sheets.items():
        if len(sheets) > 1:
            story.append(Paragraph(sheet_name, styles["SectionHeader"]))

        story.append(Paragraph(
            f"{len(df)} rows &times; {len(df.columns)} columns",
            styles["DocSubtitle"]
        ))
        story.append(Spacer(1, 8))

        # Build table data
        headers = [str(c) for c in df.columns.tolist()]
        table_data = [headers]

        for _, row in df.iterrows():
            cells = []
            for val in row:
                if pd.isna(val):
                    cells.append("")
                else:
                    cells.append(str(val))
            table_data.append(cells)

        if table_data:
            col_widths = None
            page_w = page_size[0] - margin_mm * 2 * mm
            num_cols = len(headers)
            if num_cols > 0:
                w = page_w / num_cols
                col_widths = [w] * num_cols

            t = Table(table_data, colWidths=col_widths, repeatRows=1)

            style_cmds = [
                ("BACKGROUND", (0, 0), (-1, 0), HexColor("#1E293B")),
                ("TEXTCOLOR", (0, 0), (-1, 0), white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, 0), 9),
                ("FONTSIZE", (0, 1), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
                ("TOPPADDING", (0, 0), (-1, 0), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [HexColor("#F8FAFC"), white]),
                ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#E2E8F0")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]

            t.setStyle(TableStyle(style_cmds))
            story.append(t)
            story.append(Spacer(1, 16))

    def on_page(canvas, doc):
        add_watermark_to_canvas(canvas, doc, options.watermark)
        if options.add_page_numbers:
            add_page_number(canvas, doc)

    pdf_doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


