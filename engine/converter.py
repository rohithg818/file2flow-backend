def convert_to_pdf(file_path: str, options: Optional[ConversionOptions] = None) -> bytes:
    if options is None:
        options = ConversionOptions()

    ext = Path(file_path).suffix.lower()

    converters = {
        ".docx": lambda: convert_docx(file_path, options),
        ".doc": lambda: convert_docx(file_path, options),
        ".xlsx": lambda: convert_spreadsheet(file_path, options, is_csv=False),
        ".xls": lambda: convert_spreadsheet(file_path, options, is_csv=False),
        ".csv": lambda: convert_spreadsheet(file_path, options, is_csv=True),
        ".pptx": lambda: convert_pptx(file_path, options),
        ".ppt": lambda: convert_pptx(file_path, options),
        ".json": lambda: convert_json(file_path, options),
        ".md": lambda: convert_markdown(file_path, options),
        ".markdown": lambda: convert_markdown(file_path, options),
        ".html": lambda: convert_html(file_path, options),
        ".htm": lambda: convert_html(file_path, options),
        ".txt": lambda: convert_text(file_path, options),
        ".rtf": lambda: convert_text(file_path, options),
        ".png": lambda: convert_image(file_path, options),
        ".jpg": lambda: convert_image(file_path, options),
        ".jpeg": lambda: convert_image(file_path, options),
        ".webp": lambda: convert_image(file_path, options),
        ".gif": lambda: convert_image(file_path, options),
        ".bmp": lambda: convert_image(file_path, options),
        ".svg": lambda: convert_text(file_path, options),
    }

    converter = converters.get(ext)
    if converter is None:
        raise ValueError(f"Unsupported format: {ext}")

    return converter()
